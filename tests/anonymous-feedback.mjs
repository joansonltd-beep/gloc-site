import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFileSync} from 'node:fs';
const storage=readFileSync('src/lib/dashboard/anonymous-feedback.ts','utf8').replace(/^import .*;\r?\n/gm,'');
const route=readFileSync('src/app/api/anonymous-feedback/route.ts','utf8').replace(/^import .*;\r?\n/gm,'');
const shim=`
class Conflict extends Error {}
let saved, version=0, conflicts=0, unavailable=false;
const sameOrigin=r=>r.headers.get('origin')===new URL(r.url).origin;
const readDocument=async(path,initial)=>{assertPath(path);if(unavailable)throw Error('Unavailable');return {value:structuredClone(saved??initial),etag:version}};
const assertPath=path=>{if(path!=='dashboard/anonymous-feedback-v1.json')throw Error('Unexpected path')};
const writeDocument=async(path,value,etag)=>{assertPath(path);if(conflicts){conflicts--;version++;throw new Conflict()};if(etag!==version)throw new Conflict();saved=structuredClone(value);version++};
export const failStorage=()=>unavailable=true;
export const causeConflict=()=>conflicts=1;
`;
const code=ts.transpileModule(shim+storage+route,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const feedback=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const input={id:'0a2a9cc3-46ed-415d-8ce3-7070cc2d49fc',username:'Quiet reader',message:'I am concerned about cost.'};
const post=(body=input,origin='https://test.invalid')=>feedback.POST(new Request('https://test.invalid/api/anonymous-feedback',{method:'POST',headers:{origin,'content-type':'application/json'},body:typeof body==='string'?body:JSON.stringify(body)}));
assert.equal((await post(input,'https://elsewhere.invalid')).status,403);
for(const body of [null,[],{}, {...input,username:'x'.repeat(41)},{...input,username:'first\nsecond'},{...input,message:' '},{...input,message:'x'.repeat(2001)},{...input,id:'invalid'}])assert.equal((await post(body)).status,400);
assert.equal((await post('{')).status,400);
assert.equal((await post('x'.repeat(12001))).status,413);
assert.equal((await post({...input,website:'spam.invalid'})).status,200);
assert.equal((await feedback.feedbackResponses()).length,0);
feedback.causeConflict();
assert.equal((await post()).status,201);
assert.equal((await post()).status,201);
assert.equal((await feedback.feedbackResponses()).length,1);
const anonymous={...input,id:'0a2a9cc3-46ed-415d-8ce3-7070cc2d49fd',username:'',message:'<script>alert(1)</script>'};
assert.equal((await post(anonymous)).status,201);
const responses=await feedback.feedbackResponses();
assert.equal(responses.length,2);
assert.equal(responses[0].username,'');
assert.equal(responses[0].message,anonymous.message);
assert.deepEqual(Object.keys(responses[0]).sort(),['id','message','receivedAt','username']);
assert.equal((await post({...input,message:'Changed retry'})).status,503);
assert.equal((await feedback.feedbackResponses()).length,2);
feedback.failStorage();
assert.equal((await post()).status,503);
console.log('Anonymous feedback checks passed: validation, origin protection, honeypot, private storage, retries and storage failure.');
